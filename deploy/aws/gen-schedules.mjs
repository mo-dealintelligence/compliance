#!/usr/bin/env node
/**
 * Emits serverless `events` for every cron task in a generated
 * _schedules.json, so EventBridge invokes the worker with { source, taskId }.
 *
 *   node deploy/aws/gen-schedules.mjs apps/api/src/trigger/_schedules.json > deploy/aws/api/schedules.yml
 */
import { readFileSync } from 'node:fs';

const file = process.argv[2];
const schedules = JSON.parse(readFileSync(file, 'utf8'));
const lines = ['# GENERATED by deploy/aws/gen-schedules.mjs — do not edit.', 'events:'];
for (const s of schedules) {
  const [min, hour, dom, mon, dow] = s.cron.trim().split(/\s+/);
  // EventBridge cron: 6 fields, '?' for one of day-of-month/day-of-week.
  const ebDom = dow !== '*' ? '?' : dom;
  // EventBridge numbers days 1=SUN..7=SAT (cron uses 0/7=SUN, 1=MON): use names.
  const names = ['SUN', 'MON', 'TUE', 'WED', 'THU', 'FRI', 'SAT', 'SUN'];
  const ebDow = dow === '*' ? '?' : dow.replace(/\d/g, (d) => names[Number(d)]);
  const expr = `cron(${min} ${hour} ${ebDom} ${mon} ${ebDow} *)`;
  lines.push(
    `  - schedule:`,
    `      name: \${self:service}-${s.id}`,
    `      description: '${s.id} (${s.cron})'`,
    `      rate: ${expr}`,
    `      input: { source: schedule, taskId: '${s.id}' }`,
  );
}
process.stdout.write(lines.join('\n') + '\n');
