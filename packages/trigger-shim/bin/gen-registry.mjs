#!/usr/bin/env node
/**
 * Generates a registry module that imports every task file in a trigger
 * directory (so each task registers with the shim), and a schedules JSON
 * listing cron tasks for serverless.yml.
 *
 *   node packages/trigger-shim/bin/gen-registry.mjs apps/api/src/trigger
 *   node packages/trigger-shim/bin/gen-registry.mjs apps/app/src/trigger/tasks
 *
 * Writes <dir>/_registry.ts and <dir>/_schedules.json.
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const dir = process.argv[2];
if (!dir) {
  console.error('usage: gen-registry.mjs <trigger dir>');
  process.exit(1);
}

const SKIP = /(\.spec\.|\.test\.|_registry\.ts$|\/lib\/|\/utils\/|\/types\.ts$|\/helpers?\/|\/shared\/)/;
const TASK_DECL = /\b(task|schemaTask|schedules\.task)\s*\(\s*\{/;
const SCHEDULE = /schedules\.task\s*\(\s*\{[\s\S]*?id:\s*['"]([^'"]+)['"][\s\S]*?cron:\s*['"]([^'"]+)['"]/g;

function walk(d, out = []) {
  for (const name of readdirSync(d)) {
    const p = join(d, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (p.endsWith('.ts') && !SKIP.test(p)) out.push(p);
  }
  return out;
}

const files = walk(dir).filter((f) => TASK_DECL.test(readFileSync(f, 'utf8')));
const schedules = [];
for (const f of files) {
  const src = readFileSync(f, 'utf8');
  for (const m of src.matchAll(SCHEDULE)) schedules.push({ id: m[1], cron: m[2], file: relative(dir, f) });
}

const lines = files
  .map((f) => './' + relative(dir, f).replace(/\\/g, '/').replace(/\.ts$/, ''))
  .sort()
  .map((p) => `import '${p}';`);

writeFileSync(
  join(dir, '_registry.ts'),
  `// GENERATED by packages/trigger-shim/bin/gen-registry.mjs — do not edit.\n// Importing each task module registers it with the @trigger.dev/sdk shim.\n${lines.join('\n')}\n`,
);
writeFileSync(join(dir, '_schedules.json'), JSON.stringify(schedules, null, 2) + '\n');
console.log(`${files.length} task modules, ${schedules.length} schedules -> ${dir}/_registry.ts`);
